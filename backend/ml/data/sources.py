class DownloadUnavailable(RuntimeError):
    """The single download attempt failed. Callers fall back to synthetic data."""


def download_uci(force: bool = False) -> Path:
    """
    Fetch the UCI archive, **once**.

    Returns the path to the extracted text file. Raises `DownloadUnavailable`
    rather than retrying, so the caller can fall back immediately. A file already
    on disk is reused unless `force` is set.
    """
    if UCI_LOCAL.exists() and not force:
        return UCI_LOCAL

    RAW_DIR.mkdir(parents=True, exist_ok=True)
    try:
        request = urllib.request.Request(
            UCI_URL, headers={"User-Agent": "EcoTrack/0.1 (research project)"}
        )
        with urllib.request.urlopen(request, timeout=DOWNLOAD_TIMEOUT) as response:
            payload = response.read()
    except (urllib.error.URLError, urllib.error.HTTPError, TimeoutError, OSError) as error:
        raise DownloadUnavailable(f"Could not download the UCI dataset: {error}") from error

    try:
        with zipfile.ZipFile(io.BytesIO(payload)) as archive:
            names = archive.namelist()
            member = UCI_MEMBER if UCI_MEMBER in names else next(
                (name for name in names if name.endswith(".txt")), None
            )
            if member is None:
                raise DownloadUnavailable(
                    f"The UCI archive contained no .txt member; found {names}."
                )
            UCI_LOCAL.write_bytes(archive.read(member))
    except zipfile.BadZipFile as error:
        raise DownloadUnavailable(
            f"The UCI download was not a valid zip archive: {error}"
        ) from error

    return UCI_LOCAL


def uci_available() -> bool:
    """True when the raw file is already on disk, with no network access."""
    return UCI_LOCAL.exists()
