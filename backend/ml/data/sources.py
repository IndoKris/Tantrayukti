"""
Raw data sources and their provenance.

Two sources feed the models:

1. **UCI "Individual household electric power consumption"** - real measured data
   from one household near Paris, 1-minute sampling, December 2006 to November
   2010. One download attempt is made; if it fails the pipeline falls back to the
   synthetic generator and **labels every output as synthetic**, per the plan's
   fallback rule.

2. **Synthetic grid emission factor rows** - there is no public hourly CO2
   intensity series for the Indian grid that this project can download, so the
   Phase 12 random forest trains on a generated series whose *shape* is plausible
   (coal-heavy baseload overnight, solar dilution at midday, peaking plants in
   the evening). It is **not measured data** and is never presented as such.

Provenance is written to a JSON sidecar next to every processed file, so a
downstream model or document can state where its numbers came from rather than
assuming they are real.

**Units in the UCI data, which are a trap this project cares about:**

* `Global_active_power`   - **kilowatts** (instantaneous), not kWh
* `Global_reactive_power` - kilovolt-amperes reactive
* `Voltage`               - volts
* `Global_intensity`      - amperes
* `Sub_metering_1/2/3`    - **watt-hours** of active energy per minute

So the active power column and the sub-metering columns are in different unit
families. `clean.py` converts both into one explicit kWh-per-interval column and
names it accordingly.
"""

from __future__ import annotations

import io
import json
import urllib.error
import urllib.request
import zipfile
from dataclasses import asdict, dataclass, field
from datetime import UTC, datetime
from pathlib import Path

#: Root of the ml package, so paths work regardless of the caller's cwd.
ML_DIR = Path(__file__).resolve().parent.parent
RAW_DIR = ML_DIR / "data" / "raw"
PROCESSED_DIR = ML_DIR / "data" / "processed"
ARTIFACTS_DIR = ML_DIR / "artifacts"

#: UCI archive URL. Tried exactly once - never retried in a loop (plan rule 5).
UCI_URL = (
    "https://archive.ics.uci.edu/static/public/235/"
    "individual+household+electric+power+consumption.zip"
)
UCI_MEMBER = "household_power_consumption.txt"
UCI_LOCAL = RAW_DIR / UCI_MEMBER

#: Seconds before the single download attempt is abandoned.
DOWNLOAD_TIMEOUT = 60


@dataclass
class Provenance:
    """Where a dataset came from. Serialised beside every processed file."""

    dataset: str
    is_synthetic: bool
    source: str
    licence: str = ""
    units: dict[str, str] = field(default_factory=dict)
    rows: int | None = None
    first_timestamp: str | None = None
    last_timestamp: str | None = None
    notes: list[str] = field(default_factory=list)
    generated_at: str = field(
        default_factory=lambda: datetime.now(UTC).isoformat(timespec="seconds")
    )

    def as_dict(self) -> dict:
        return asdict(self)

    def write(self, path: Path) -> Path:
        """Write the sidecar as `<path>.provenance.json`."""
        target = path.with_suffix(path.suffix + ".provenance.json")
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(json.dumps(self.as_dict(), indent=2), encoding="utf-8")
        return target


